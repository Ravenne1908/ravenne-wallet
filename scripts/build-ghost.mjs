/* Build the embedded ghost splash asset.
 *
 * Source: gost/animation.json (GhosttyFetch, MIT — see THIRD_PARTY_NOTICES.md).
 * Output: assets/ghost.js — a gzip+base64 blob imported by ravenne.js, so the
 * splash still works from the single-file bundle and the standalone .exe.
 *
 * Usage: node scripts/build-ghost.mjs [source.json] [output.js]
 */
import fs from "node:fs";
import path from "node:path";
import zlib from "node:zlib";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const src = path.resolve(root, process.argv[2] || "gost/animation.json");
const out = path.resolve(root, process.argv[3] || "assets/ghost.js");

const raw = fs.readFileSync(src);
const data = JSON.parse(raw.toString("utf8"));
const frames = Array.isArray(data.frames) ? data.frames : null;
if (!frames?.length) throw new Error(`no frames in ${src}`);
const width = Number(data.max_width);
const height = Number(data.lines_per_frame);
if (!(width > 0) || !(height > 0)) throw new Error(`invalid dimensions in ${src}`);

const gz = zlib.gzipSync(raw, { level: 9 });
const sha = crypto.createHash("sha256").update(raw).digest("hex");

const body = `/* Generated by scripts/build-ghost.mjs — do not edit by hand.
 *
 * Ghost animation: GhosttyFetch (https://github.com/BarutSRB/GhosttyFetch),
 * MIT licensed. Ghostty logo: https://ghostty.org/ — see THIRD_PARTY_NOTICES.md.
 * Source: ${path.relative(root, src).replace(/\\/g, "/")} (${sha.slice(0, 16)}…)
 */
export const GHOST_ASSET = {
  v: 1,
  width: ${width},
  height: ${height},
  frames: ${frames.length},
  sha256: "${sha}",
  gz: "${gz.toString("base64")}",
};
`;

fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, body);
console.log(`ghost asset: ${frames.length} frames, ${width}x${height}, ` +
  `${(gz.length / 1024).toFixed(1)} KiB gz -> ${path.relative(root, out)}`);
